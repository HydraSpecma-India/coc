export function translate(lang: Lang, key: MessageKey, vars?: Record<string, string | number>): string {
  const text = MESSAGES[lang]?.[key] ?? en[key] ?? key;
  return vars ? text.replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? String(vars[k]) : `{${k}}`)) : text;
}
